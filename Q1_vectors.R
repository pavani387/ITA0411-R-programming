# Numeric vector
num <- c(10, 20, 30, 40, 50)

# Character vector
char <- c("Apple", "Mango", "Orange", "Banana")

# Logical vector
logi <- c(TRUE, FALSE, TRUE, FALSE)

# Display contents
print(num)
print(char)
print(logi)

# Display data types
print(typeof(num))
print(typeof(char))
print(typeof(logi))